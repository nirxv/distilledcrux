/**
 * Generates lib/pdfMascot.ts: the owl, as PNG data URIs, for the PDFs that
 * /api/generate-pdf renders (Save PDF in chat).
 *
 * react-pdf cannot draw an SVG file, so the owl goes in as a PNG, rendered at
 * four times its printed size to stay sharp on paper. It is inlined as a data
 * URI rather than read from public/ at request time: the serverless function
 * only carries the files the bundler traced, and an image it missed would
 * take every PDF down with it.
 *
 *   node scripts/gen-pdf-mascot.mjs
 *
 * Run it again whenever an owl in public/mascot changes.
 */
import { writeFileSync } from 'node:fs';
import sharp from 'sharp';

// Width in pixels: four times the width each is printed at in the PDF.
const POSES = [
  { name: 'OWL_PEEK', file: 'public/mascot/owl.svg', width: 256 },
  { name: 'OWL_READING', file: 'public/mascot/owl-reading.svg', width: 96 },
];

let out = `// Generated by scripts/gen-pdf-mascot.mjs from public/mascot. Do not edit.\n`;
for (const { name, file, width } of POSES) {
  const png = await sharp(file, { density: 600 })
    .resize({ width })
    .png({ compressionLevel: 9, palette: true })
    .toBuffer();
  const { height } = await sharp(png).metadata();
  out += `\n/** ${file}, ${width}×${height}. */\nexport const ${name} = 'data:image/png;base64,${png.toString('base64')}';\n`;
  out += `export const ${name}_RATIO = ${(height / width).toFixed(4)};\n`;
  console.log(`${name}: ${width}×${height}, ${png.length} bytes`);
}
writeFileSync('lib/pdfMascot.ts', out);
