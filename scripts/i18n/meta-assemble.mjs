#!/usr/bin/env node
/**
 * Build lib/notesHi/<subject>.ts from the translated metadata.
 *
 *   node scripts/i18n/meta-assemble.mjs [subject]
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const SUBJECTS = ['sociology', 'anthropology', 'polsci', 'geography', 'pub-admin'];
const only = process.argv[2];
if (only && !SUBJECTS.includes(only)) {
  console.error(`unknown subject: ${only}`);
  process.exit(1);
}

for (const subject of SUBJECTS) {
  if (only && subject !== only) continue;
  const EN = join(ROOT, 'scripts', 'i18n', 'work', 'meta', 'en', `${subject}.json`);
  const HI = join(ROOT, 'scripts', 'i18n', 'work', 'meta', 'hi', `${subject}.json`);
  if (!existsSync(HI)) continue;

  const en = JSON.parse(readFileSync(EN, 'utf8'));
  const hi = JSON.parse(readFileSync(HI, 'utf8'));

  const sectionLines = en.sections
    .filter((s) => hi.sections?.[s])
    .map((s) => `  ${JSON.stringify(s)}: ${JSON.stringify(hi.sections[s])},`)
    .join('\n');

  const noteLines = en.notes
    .filter((n) => hi.notes?.[n.slug])
    .map((n) => {
      const t = hi.notes[n.slug];
      return `  ${JSON.stringify(n.slug)}: { title: ${JSON.stringify(t.title)}, description: ${JSON.stringify(t.description)}, subtopics: ${JSON.stringify(t.subtopics)} },`;
    })
    .join('\n');

  const out = `// AUTO-GENERATED by scripts/i18n/meta-assemble.mjs. Do not edit by hand.
//
// Hindi titles, descriptions, subtopics and section names for ${subject}.
// lib/notes.ts stays the source and the key.

export const SECTION_HI: Record<string, string> = {
${sectionLines}
};

export type NoteHi = { title: string; description: string; subtopics: string[] };

export const NOTE_HI: Record<string, NoteHi> = {
${noteLines}
};
`;

  const dir = join(ROOT, 'lib', 'notesHi');
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, `${subject}.ts`), out, 'utf8');
  console.log(`${subject}: ${en.notes.length} notes -> lib/notesHi/${subject}.ts`);
}
