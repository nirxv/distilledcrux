#!/usr/bin/env node
/**
 * Build lib/noteContentHi/<subject>.ts from the translated HTML parts.
 *
 *   node scripts/i18n/assemble.mjs            # every subject
 *   node scripts/i18n/assemble.mjs sociology
 *
 * Parts live at lib/noteContentHi/parts/<subject>/<slug>.html and are written
 * by the translating agents. Order follows the English file, so the Hindi file
 * stays a view of the same corpus. Backticks and ${ are escaped for the
 * template literal; everything else is passed through untouched.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const SUBJECTS = ['sociology', 'anthropology', 'polsci', 'geography', 'pub-admin'];
const VAR = {
  sociology: 'sociologyNoteContentHi',
  anthropology: 'anthropologyNoteContentHi',
  polsci: 'polsciNoteContentHi',
  geography: 'geographyNoteContentHi',
  'pub-admin': 'pubAdminNoteContentHi',
};

const only = process.argv[2];
if (only && !SUBJECTS.includes(only)) {
  console.error(`unknown subject: ${only}`);
  process.exit(1);
}

for (const subject of SUBJECTS) {
  if (only && subject !== only) continue;
  const enPath = join(ROOT, 'lib', 'noteContent', `${subject}.ts`);
  if (!existsSync(enPath)) continue;
  const en = readFileSync(enPath, 'utf8');
  const order = [...en.matchAll(/^\s+'([^']+)':\s*`/gm)].map((m) => m[1]);
  const partsDir = join(ROOT, 'lib', 'noteContentHi', 'parts', subject);
  const have = existsSync(partsDir) ? new Set(readdirSync(partsDir).filter((f) => f.endsWith('.html')).map((f) => f.slice(0, -5))) : new Set();

  const bodies = [];
  let missing = 0;
  for (const slug of order) {
    if (!have.has(slug)) {
      missing++;
      continue;
    }
    const html = readFileSync(join(partsDir, `${slug}.html`), 'utf8')
      .trim()
      .replace(/\\/g, '\\\\')
      .replace(/`/g, '\\`')
      .replace(/\$\{/g, '\\${');
    bodies.push(`  '${slug}': \`\n${html}\n\`,`);
  }

  const out = `// AUTO-GENERATED by scripts/i18n/assemble.mjs. Do not edit by hand:
// edit lib/noteContentHi/parts/${subject}/<slug>.html and reassemble.
//
// Hindi note bodies for ${subject}. ${bodies.length}/${order.length} notes translated.

export const ${VAR[subject]}: Record<string, string> = {
${bodies.join('\n')}
};
`;

  const dest = join(ROOT, 'lib', 'noteContentHi', `${subject}.ts`);
  writeFileSync(dest, out, 'utf8');
  console.log(`${subject}: ${bodies.length}/${order.length} notes -> ${dest}${missing ? ` (${missing} pending)` : ''}`);
}
