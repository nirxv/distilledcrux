#!/usr/bin/env node
/**
 * Merge translated PYQ batches into one Hindi bank per subject.
 *
 *   node scripts/i18n/pyq-assemble.mjs            # all subjects
 *   node scripts/i18n/pyq-assemble.mjs sociology
 *
 * Reads every scripts/i18n/work/pyq/hi/<subject>-*.json and writes
 * lib/pyqHi/<subject>.ts, keyed by question id exactly as the English bank is.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const SUBJECTS = ['sociology', 'anthropology', 'polsci', 'geography', 'pub-admin'];
const only = process.argv[2];
if (only && !SUBJECTS.includes(only)) {
  console.error(`unknown subject: ${only}`);
  process.exit(1);
}

const HI_DIR = join(ROOT, 'scripts', 'i18n', 'work', 'pyq', 'hi');
const OUT_DIR = join(ROOT, 'lib', 'pyqHi');
mkdirSync(OUT_DIR, { recursive: true });

for (const subject of SUBJECTS) {
  if (only && subject !== only) continue;
  const files = existsSync(HI_DIR)
    ? readdirSync(HI_DIR).filter((f) => f.startsWith(`${subject}-`) && f.endsWith('.json') && !f.includes('-topics'))
    : [];
  const bank = {};
  let duplicate = 0;
  for (const f of files) {
    const part = JSON.parse(readFileSync(join(HI_DIR, f), 'utf8'));
    for (const [id, text] of Object.entries(part)) {
      if (bank[id] !== undefined) duplicate++;
      bank[id] = String(text).trim();
    }
  }
  const ids = Object.keys(bank).sort((a, b) => Number(a) - Number(b));
  const body = ids
    .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(bank[id])},`)
    .join('\n');
  const out = `// AUTO-GENERATED by scripts/i18n/pyq-assemble.mjs. Do not edit by hand.
//
// Hindi question text for ${subject}, keyed by the English bank's id.
// ${ids.length} questions translated.

export const pyqHi: Record<string, string> = {
${body}
};
`;
  writeFileSync(join(OUT_DIR, `${subject}.ts`), out, 'utf8');
  console.log(`${subject}: ${ids.length} questions${duplicate ? ` (${duplicate} duplicate ids merged)` : ''}`);
}

// Topic and microtheme labels, one map for all subjects.
{
  const bySubject = {};
  for (const subject of SUBJECTS) {
    const f = join(ROOT, 'scripts', 'i18n', 'work', 'pyq', 'hi', `${subject}-topics.json`);
    if (existsSync(f)) bySubject[subject] = JSON.parse(readFileSync(f, 'utf8'));
  }
  if (Object.keys(bySubject).length) {
    writeFileSync(
      join(OUT_DIR, 'topics.ts'),
      `// AUTO-GENERATED by scripts/i18n/pyq-assemble.mjs. English label -> Hindi label.\n\nexport const PYQ_TOPICS_HI: Record<string, Record<string, string>> = ${JSON.stringify(bySubject, null, 1)};\n`,
      'utf8',
    );
    console.log(`topics -> lib/pyqHi/topics.ts`);
  }
}
